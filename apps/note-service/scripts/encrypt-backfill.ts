import 'reflect-metadata';
import { DataSource } from 'typeorm';
import { join, resolve } from 'path';
import { loadMasterKeyFromEnv } from '@life/crypto';
import { Note } from '../src/notes/note.entity';
import { Tag } from '../src/notes/tag.entity';
import { UserKeys } from '../src/keys/user-keys.entity';
import { MASTER_KEY_ENV } from '../src/keys/keys.service';
import {
  applyBackfill,
  formatBackfillReport,
  planBackfill,
  type BackfillReport,
} from '../src/keys/backfill';

/**
 * `notes-backfill` entry (`SPEC-notes-backfill` Behavior + `D10`). Thin CLI over
 * the tested core in `src/keys/backfill.ts`; run via the workspace convention:
 *
 *   npm run backfill-encrypt -w @life/note-service -- --dry-run
 *   npm run backfill-encrypt -w @life/note-service
 *
 * Deploy Checklist (human-run) — verbatim from `docs/specs/SPEC-notes-backfill.md`:
 *
 * 1. Stop the stack (`docker compose down`).
 * 2. Backup: copy the note-service DB file to `<db>.pre-encrypt-<date>` (rollback path).
 * 3. `NOTE_MASTER_KEY=<key> npm run backfill-encrypt -w @life/note-service -- --dry-run` → review counts.
 * 4. `NOTE_MASTER_KEY=<key> npm run backfill-encrypt -w @life/note-service` (apply).
 * 5. Boot (`docker compose up -d`), verify counts endpoint/UX (phone check).
 * 6. Rollback if needed: stop, restore the backup file, boot.
 *
 * Prod `NOTE_MASTER_KEY` is generated by the human (`openssl rand -base64 32`); it
 * never enters the repo (hard line: no secrets).
 *
 * The DB path follows the `backfill-owner` convention (`NOTE_DB_PATH` anchored at
 * `INIT_CWD ?? cwd`, defaulting to the relative `data/life.db`), and the
 * connection mirrors `app.module.ts` exactly except `synchronize: false` — a
 * migration must never mutate schema implicitly.
 */

const DEFAULT_NOTE_DB_PATH = join('data', 'life.db');

/** Anchor env-relative paths where npm was invoked from (`INIT_CWD`), like backfill-owner. */
export function resolveDbPath(env: NodeJS.ProcessEnv = process.env): string {
  const root = env.INIT_CWD ?? process.cwd();
  return resolve(root, env.NOTE_DB_PATH || DEFAULT_NOTE_DB_PATH);
}

/** Mirror of `app.module.ts`'s better-sqlite3 DataSource, with `synchronize` off. */
export function createDataSource(dbPath: string): DataSource {
  return new DataSource({
    type: 'better-sqlite3',
    database: dbPath,
    entities: [Note, Tag, UserKeys],
    synchronize: false,
  });
}

export interface BackfillCliDeps {
  /** Inject for testing; defaults to opening the mirror DataSource. */
  dataSource?: DataSource;
  env?: NodeJS.ProcessEnv;
  print?: (line: string) => void;
  printError?: (line: string) => void;
}

/**
 * CLI body. Returns the exit code instead of terminating the process so the entry
 * stays honest under test. Dry-run plans; default applies.
 */
export async function main(
  argv: string[] = process.argv.slice(2),
  deps: BackfillCliDeps = {},
): Promise<number> {
  const env = deps.env ?? process.env;
  const print = deps.print ?? ((line: string) => console.log(line));
  const printError = deps.printError ?? ((line: string) => console.error(line));
  const dryRun = argv.includes('--dry-run');

  const ownDataSource = deps.dataSource === undefined;
  let ds: DataSource | undefined = deps.dataSource;
  try {
    const masterKey = loadMasterKeyFromEnv(MASTER_KEY_ENV);
    if (!ds) {
      ds = createDataSource(resolveDbPath(env));
      await ds.initialize();
    }
    const report: BackfillReport = dryRun
      ? await planBackfill(ds)
      : await applyBackfill(ds, masterKey);
    print(formatBackfillReport(report));
    return 0;
  } catch (err) {
    printError(
      `notes-backfill failed: ${err instanceof Error ? err.message : 'unknown error'}`,
    );
    return 1;
  } finally {
    if (ownDataSource && ds?.isInitialized) {
      await ds.destroy();
    }
  }
}

/* istanbul ignore next — CLI entry, exercised manually at deploy time */
if (require.main === module) {
  void main().then((code) => {
    process.exitCode = code;
  });
}
