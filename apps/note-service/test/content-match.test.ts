/**
 * `notes-at-rest` T4 — decrypt-then-match search + tag filtering
 * (`SPEC-notes-at-rest` Search & Tag Filtering).
 *
 * The parity proof is empirical: expected `LIKE` results are generated by a real
 * query on the same temp sqlite DB, never hand-coded. Every fixture DB is a
 * throwaway under the OS temp dir; this suite NEVER opens anything under
 * `apps/note-service/data/` (the hard line).
 */

const MASTER_KEY = Buffer.alloc(32, 0x2a);
const SUB = 'user-a';

interface Harness {
  dataSource: DataSource;
  service: NotesService;
  dir: string;
  /** Every SQL statement the driver emitted, for the metadata-only assertion. */
  log: string[];
}

function makeLogger(sink: string[]): unknown {
  return {
    logQuery: (query: string) => {
      sink.push(query);
    },
    logQueryError: () => undefined,
    logQuerySlow: () => undefined,
    logSchemaBuild: () => undefined,
    logMigration: () => undefined,
    log: () => undefined,
  };
}

async function makeHarness(): Promise<Harness> {
  const dir = mkdtempSync(join(tmpdir(), 'note-match-'));
  const log: string[] = [];
  const dataSource = new DataSource({
    type: 'better-sqlite3',
    database: join(dir, 'notes.db'),
    entities: [Note, NoteTag, UserKeys],
    synchronize: true,
    logging: true,
    logger: makeLogger(log) as never,
  });
  await dataSource.initialize();
  const keys = new KeysService(dataSource.getRepository(UserKeys), MASTER_KEY);
  const service = new NotesService(
    dataSource.getRepository(Note),
    dataSource.getRepository(NoteTag),
    new NotesCache(null),
    keys,
  );
  return { dataSource, service, dir, log };
}

/** Expected result straight from sqlite: `text LIKE pattern` (1/0 → boolean). */
async function sqliteLike(ds: DataSource, text: string, pattern: string): Promise<boolean> {
  const rows = await ds.query('SELECT (? LIKE ?) AS m', [text, pattern]);
  return Number(rows[0].m) === 1;
}

/** Create a note through the service, then pin its `createdAt` for ordering tests. */
async function seedNote(
  h: Harness,
  body: string,
  tagIds: number[] = [],
  createdAt?: Date,
): Promise<{ id: string }> {
  const dto = await h.service.create(SUB, body, tagIds);
  if (createdAt) {
    await h.dataSource.getRepository(Note).update(dto.id, { createdAt });
  }
  return dto;
}

/** Insert a legacy (pre-encryption) plaintext row directly, bypassing the service. */
async function seedLegacyNote(h: Harness, body: string, createdAt: Date): Promise<string> {
  const id = randomUUID();
  await h.dataSource.getRepository(Note).insert({
    id,
    body,
    ownerSub: SUB,
    version: 0,
    deletedAt: null,
    createdAt,
    updatedAt: createdAt,
  });
  return id;
}

describe('notes-at-rest T4: LIKE-parity comparator', () => {
  let h: Harness;

  beforeEach(async () => {
    h = await makeHarness();
  });

  afterEach(async () => {
    await h.dataSource.destroy();
    rmSync(h.dir, { recursive: true, force: true });
  });

  it('1. equals SQLite LIKE over an ASCII corpus (empirically generated expectations)', async () => {
    // `q` is wrapped exactly as today's binding did: `%${q}%`. The corpus covers
    // case variants, `%`/`_` wildcards typed by the user, empty patterns, and
    // leading/trailing characters. ASCII only — the Unicode fold is the
    // documented deviation and is asserted separately.
    const texts = [
      'Hello World',
      'hello world',
      'HELLO',
      'abc_def_ghi',
      '100% pure',
      'under_score',
      'MiXeD CaSe',
      'trailing ',
      ' leading',
      'a',
      '_',
      '%',
      '',
    ];
    const queries = [
      'hello',
      'HELLO',
      'World',
      'o w',
      'abc',
      '_def',
      '100%',
      '%',
      '_',
      'def_ghi',
      'zzz',
      '',
      'A',
      'a',
      'trailing',
      'leading',
      '% p',
    ];

    const mismatches: Array<Record<string, unknown>> = [];
    for (const text of texts) {
      for (const q of queries) {
        const pattern = `%${q}%`;
        const expected = await sqliteLike(h.dataSource, text, pattern);
        const actual = likeMatch(text, pattern);
        if (actual !== expected) mismatches.push({ text, q, pattern, expected, actual });
      }
    }

    expect(mismatches).toEqual([]);
  });

  it('6. documents the Unicode-folding deviation (broader fold than SQLite LIKE)', async () => {
    // SQLite `LIKE` folds ASCII A–Z only, so a non-ASCII case pair does not match.
    expect(await sqliteLike(h.dataSource, 'CAFÉ', '%café%')).toBe(false);
    // `toLowerCase()` folds Unicode too, so the comparator matches. This is the
    // accepted, documented deviation (SPEC-notes-at-rest parity contract).
    expect(likeMatch('CAFÉ', '%café%')).toBe(true);

    // `İ` (U+0130) lowercases to `i` + a combining dot, so `%i%` matches in JS.
    expect(likeMatch('İstanbul', '%i%')).toBe(true);
    // SQLite's ASCII-only fold does not see an `i` there.
    expect(await sqliteLike(h.dataSource, 'İstanbul', '%i%')).toBe(false);
  });
});

describe('notes-at-rest T4: decrypt-then-match service', () => {
  let h: Harness;

  beforeEach(async () => {
    h = await makeHarness();
  });

  afterEach(async () => {
    await h.dataSource.destroy();
    rmSync(h.dir, { recursive: true, force: true });
  });

  it('2. filters `q` over decrypted bodies, case-insensitively, and via a legacy row', async () => {
    const alpha = await seedNote(h, 'alpha beta');
    const upper = await seedNote(h, 'ALPHA gamma');
    await seedNote(h, 'gamma delta');
    // A pre-encryption row matches on its raw value (dual-read pass-through).
    const legacy = await seedLegacyNote(h, 'legacy alpha body', new Date('2024-01-01T00:00:00Z'));

    const found = await h.service.findAll(SUB, { q: 'alpha' });
    expect(found.notes.map((n) => n.id).sort()).toEqual([alpha.id, upper.id, legacy].sort());
    expect(found.notes.map((n) => n.body)).toContain('legacy alpha body');

    const none = await h.service.findAll(SUB, { q: 'no-such-substring' });
    expect(none.notes).toHaveLength(0);

    // A user-typed `_` is an active single-character wildcard, exactly as in the
    // retired SQL `LIKE`.
    const wildcard = await h.service.findAll(SUB, { q: 'alph_ beta' });
    expect(wildcard.notes.map((n) => n.id)).toEqual([alpha.id]);
  });

  it('3. filters by `tagId` and combines `q` + `tagId`', async () => {
    const work = await seedNote(h, 'hello world', [1]);
    const idea = await seedNote(h, 'hello world', [2]);
    // A second note sharing the same registry id (the filter is id-based).
    const workOther = await seedNote(h, 'other text', [1]);

    const byTag = await h.service.findAll(SUB, { tagId: 1 });
    expect(byTag.notes.map((n) => n.id).sort()).toEqual([work.id, workOther.id].sort());
    expect(byTag.notes.map((n) => n.id)).not.toContain(idea.id);

    const combined = await h.service.findAll(SUB, { q: 'hello', tagId: 1 });
    expect(combined.notes.map((n) => n.id)).toEqual([work.id]);
  });

  it('4. preserves ordering and the `id` tie-break for list and trash', async () => {
    const same = new Date('2024-03-03T00:00:00Z');
    const a = await seedNote(h, 'list a', [], same);
    const b = await seedNote(h, 'list b', [], same);
    const c = await seedNote(h, 'list c', [], same);

    const list = await h.service.findAll(SUB, {});
    expect(list.notes.map((n) => n.id)).toEqual([a.id, b.id, c.id].sort().reverse());

    // Trash: `deletedAt DESC`, then `id` DESC on a tie.
    for (const n of [a, b, c]) await h.service.remove(SUB, n.id);
    for (const n of [a, b, c]) {
      await h.dataSource.getRepository(Note).update(n.id, { deletedAt: same });
    }
    const trash = await h.service.findTrash(SUB, {});
    expect(trash.notes.map((n) => n.id)).toEqual([a.id, b.id, c.id].sort().reverse());
  });

  it('5a. pages the *filtered* set with the unchanged page shape and no dup/skip', async () => {
    const base = Date.parse('2024-04-04T00:00:00Z');
    const matching = [];
    for (let i = 0; i < 5; i++) {
      matching.push(await seedNote(h, `page match ${i}`, [], new Date(base + i * 1000)));
    }
    // Non-matching rows must not consume page slots.
    await seedNote(h, 'unrelated', [], new Date(base + 60_000));
    await seedNote(h, 'another unrelated', [], new Date(base + 61_000));

    const seen: string[] = [];
    let cursor: string | undefined;
    let pages = 0;
    do {
      const res = await h.service.findAll(SUB, { q: 'match', limit: 2, cursor });
      // Pre-change contract: `{ notes, nextCursor }` and the shared Note DTO keys.
      expect(Object.keys(res).sort()).toEqual(['nextCursor', 'notes']);
      for (const note of res.notes) {
        expect(Object.keys(note).sort()).toEqual([
          'body',
          'createdAt',
          'deletedAt',
          'id',
          'tagIds',
          'updatedAt',
          'version',
        ]);
      }
      seen.push(...res.notes.map((n) => n.id));
      cursor = res.nextCursor ?? undefined;
      pages += 1;
    } while (cursor && pages < 10);

    expect(new Set(seen).size).toBe(seen.length); // no duplicates
    expect(seen.sort()).toEqual(matching.map((n) => n.id).sort()); // no skips
  });

  it('5b. pages a same-timestamp tie without repeating the boundary row', async () => {
    // Identical timestamps make every row a tie on the primary sort key. The
    // retired SQL cursor predicate compared stored sqlite text to an ISO cursor
    // and re-emitted the boundary row here; in-memory keyset pagination must not.
    const same = new Date('2024-05-05T00:00:00Z');
    const tie: string[] = [];
    for (let i = 0; i < 5; i++) {
      tie.push((await seedNote(h, `tie match ${i}`, [], same)).id);
    }

    const seen: string[] = [];
    let cursor: string | undefined;
    let pages = 0;
    do {
      const res: NotePage = await h.service.findAll(SUB, { q: 'tie', limit: 2, cursor });
      seen.push(...res.notes.map((n) => n.id));
      cursor = res.nextCursor ?? undefined;
      pages += 1;
    } while (cursor && pages < 10);

    expect(seen).toHaveLength(5);
    expect(new Set(seen).size).toBe(5);
    expect(seen).toEqual(tie.sort().reverse());
  });

  it('keeps SQL metadata-only: no `LIKE` and no `LOWER(...)` in the read query', async () => {
    await seedNote(h, 'hello there', [1]);

    h.log.length = 0;
    await h.service.findAll(SUB, { q: 'hello', tagId: 1 });

    const contentMatching = h.log.filter((sql) => /\bLIKE\b/i.test(sql) || /\bLOWER\s*\(/i.test(sql));
    expect(contentMatching).toEqual([]);
    // The candidate fetch is present and only scoped by metadata.
    expect(h.log.some((sql) => /from "note"/i.test(sql))).toBe(true);
  });
});
