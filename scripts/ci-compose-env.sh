#!/usr/bin/env bash
# ci-compose-env.sh — write the throwaway env file the compose-boot CI job needs.
#
# Every variable this stack is REQUIRED to have at boot — not merely every
# variable `docker compose config` requires at interpolation. That distinction
# is the reason this job exists: `config` only proves interpolation succeeds, so
# a variable the code demands at boot (compose forwards it with an empty default,
# the service then throws) passes `config` and kills the container. The IdP's
# producer callbacks are the same trap in another shape — their names are
# composed at runtime (`OIDC_PRODUCER_<NAME>_REDIRECT_URIS`), so no static check
# can see a missing value at all.
#
# Variables written, and why each one is here:
#   NOTE_MASTER_KEY            content key; compose fails interpolation without it
#   TAGS_MASTER_KEY            idem
#   TODO_MASTER_KEY            idem
#   MEAL_MASTER_KEY            idem
#   FOCUS_MASTER_KEY           idem
#   FEEDBACK_MASTER_KEY        idem
#   FEEDBACK_DB_PASSWORD       Postgres role password; compose fails without it
#   FEEDBACK_RABBITMQ_PASSWORD broker password; compose fails without it
#   OIDC_APP_CLIENT_SECRET     IdP AND app throw under NODE_ENV=production, which
#                              compose sets on every service (clients.ts:41,
#                              apps/app/lib/auth/env.ts:89) — a boot crash, not
#                              an interpolation error
#   OIDC_PRODUCER_PRODUCER_A_REDIRECT_URIS  IdP throws under production
#   OIDC_PRODUCER_PRODUCER_B_REDIRECT_URIS  idem
#   OIDC_APP_REDIRECT_URI      app validates it at request time; compose forwards
#                              it to the IdP under the plural name, so a missing
#                              value also leaves the app without a callback
#   IDP_ISSUER                 app rejects an unset issuer (requireAbsoluteUrl);
#                              the IdP itself defaults, the app does not
#   OWNER_LOGIN                the app's ACCESS gate compares the forwarded
#                              `tailscale-user-login` against it. Undefined, the
#                              gate refuses every request, so the assertion that
#                              reaches the IDENTITY gate has nothing to match
#
# Destination is `<repo>/.env` and not a name of the caller's choosing:
# compose.yaml pins `env_file: .env` on all eight built services, so any other
# filename leaves interpolation satisfied and the containers without their env
# file. Writing here means the workflow's `--env-file` (interpolation) and
# compose's `env_file:` (container env) read the SAME file. `.env` is gitignored,
# so the generated file cannot be committed.
#
# Prints the path it wrote on stdout and nothing else — every value stays out of
# the log. Commentary goes to stderr, so `env_file=$(scripts/ci-compose-env.sh)`
# captures a bare path.
#
# Usage: scripts/ci-compose-env.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/.env"

# ponytail: an existing file is kept untouched, never regenerated. That is the
# idempotency the job needs (a re-run must not rotate keys mid-flight) and it
# also protects a developer's real `.env` from being overwritten by a CI-shaped
# one. Ceiling: a hand-made `.env` is trusted as-is, so a variable missing there
# surfaces as a compose boot failure, not as a warning here.
if [ -f "$DEST" ]; then
  echo "keeping existing $DEST (not regenerated)" >&2
  echo "$DEST"
  exit 0
fi

umask 077

# 32 random bytes, base64 — the exact shape `openssl rand -base64 32` produces and
# the only shape the crypto loader accepts (`packages/crypto/src/keys.ts`). A
# malformed key would fail the boot for a different reason than the one under
# test, so the value shape is part of the contract, not a detail.
master_key() { openssl rand -base64 32; }

cat >"$DEST" <<EOF
# Generated by scripts/ci-compose-env.sh for the compose-boot CI job.
# Throwaway CI values: nothing here is a secret, nothing here is reused from a
# real deployment, and this file is gitignored. Never copy it to a host.

# --- content-encryption master keys (32 bytes base64, one per service) -------
NOTE_MASTER_KEY=$(master_key)
TAGS_MASTER_KEY=$(master_key)
TODO_MASTER_KEY=$(master_key)
MEAL_MASTER_KEY=$(master_key)
FOCUS_MASTER_KEY=$(master_key)
FEEDBACK_MASTER_KEY=$(master_key)

# --- feedback service: its Postgres role and RabbitMQ user -------------------
FEEDBACK_DB_PASSWORD=$(master_key)
FEEDBACK_RABBITMQ_PASSWORD=$(master_key)

# --- IdP + app: the OIDC app client secret ----------------------------------
# Required in production by BOTH sides (no placeholder fallback): the IdP asserts
# it in its own constructor, the app when it builds its auth env. Compose sets
# NODE_ENV=production on every service, so without this the stack crashes at boot
# for a reason that has nothing to do with the deployment defect under test.
OIDC_APP_CLIENT_SECRET=ci-compose-boot-not-a-secret

# --- IdP: the producer callbacks --------------------------------------------
# Supplied here because production requires them and the point of this job is to
# boot the production shape. The names are composed at runtime in
# apps/idp/src/oidc/clients.ts, so this file is the only place a static check
# cannot reach. Values are the documented loopback callbacks.
OIDC_PRODUCER_PRODUCER_A_REDIRECT_URIS=http://localhost:8080/cb,http://127.0.0.1:8080/cb
OIDC_PRODUCER_PRODUCER_B_REDIRECT_URIS=http://localhost:8080/cb,http://127.0.0.1:8080/cb

# --- app: callback + issuer -------------------------------------------------
# Both are validated by the app rather than by compose: a relative/missing issuer
# is rejected outright, and the callback must be this app's /auth/callback. The
# IdP defaults each of them, the app does not.
OIDC_APP_REDIRECT_URI=http://127.0.0.1:3002/auth/callback
IDP_ISSUER=http://127.0.0.1:3003

# --- app: the owner the ACCESS gate admits --------------------------------
# The app's Tailscale ACCESS gate compares the 'tailscale-user-login' header against
# this value. It is a CI fixture, not a secret: nothing is served to it beyond the
# gate's own answer, and the compose-boot job sends the matching header to prove the
# gate lets the owner through to the IDENTITY gate instead of refusing.
OWNER_LOGIN=ci-compose-boot@example.com
EOF

echo "wrote $DEST (14 variables, values not printed)" >&2
echo "$DEST"
