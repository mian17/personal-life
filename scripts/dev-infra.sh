#!/usr/bin/env bash
# dev-infra.sh — throwaway Postgres + RabbitMQ for the host-run dev stack.
#
# `npm run dev:build` runs the seven services on the host, where compose's
# `postgres-feedback`/`rabbitmq-feedback` are not reachable: they live on the
# compose network and publish to the host only while the production stack is
# up. A dev run must not depend on production being up, and must never touch
# it. So dev gets its own pair, on ports prod does not own.
#
# Throwaway by construction: no volumes and `--rm`. `up` reuses a container that
# is already running (recreating it would wipe the schema its services built) and
# replaces only the missing one. Delete them and nothing of value is lost.
#
# Credentials are not invented here — they are generated by
# `scripts/setup-dev-env.sh` into `.env.development` and read back below, so the
# containers and the host-run services always agree.
#
# Usage: scripts/dev-infra.sh up|down|status
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$REPO/.env.development"

PG=personal-life-dev-pg
MQ=personal-life-dev-rabbit
# Prod owns 5432/5672 (`compose.yaml` postgres-feedback/rabbitmq-feedback).
PG_PORT=5433
MQ_PORT=5673

read_env() { # KEY -> value from the generated dev env, empty if absent
  [ -f "$ENV_FILE" ] || return 0
  sed -n "s/^$1=//p" "$ENV_FILE" | head -1
}

PG_PASSWORD="$(read_env FEEDBACK_DB_PASSWORD)"
MQ_PASSWORD="$(read_env FEEDBACK_RABBITMQ_PASSWORD)"
if [ -z "$PG_PASSWORD" ] || [ -z "$MQ_PASSWORD" ]; then
  echo "dev-infra: $ENV_FILE has no FEEDBACK_DB_PASSWORD / FEEDBACK_RABBITMQ_PASSWORD." >&2
  echo "  generate it first: bash scripts/setup-dev-env.sh" >&2
  exit 1
fi

# The first run pulls both images (postgres + rabbitmq), which can take
# minutes on a cold Docker cache - so this budget covers a pull, not just a boot.
READY_TRIES=180

wait_ready() { # name, then the readiness command
  local name="$1"
  shift
  for _ in $(seq 1 "$READY_TRIES"); do
    if "$@" >/dev/null 2>&1; then return 0; fi
    sleep 1
  done
  echo "dev-infra: $name never became ready after ${READY_TRIES}s" >&2
  echo "  inspect it: docker logs $name" >&2
  return 1
}

running() { # container name -> 0 if it is up
  [ "$(docker inspect -f '{{.State.Running}}' "$1" 2>/dev/null)" = "true" ]
}

up() {
  # Each container is checked on its own: a previous session, or an earlier
  # `dev:infra:up`, may have left one running — recreating it would wipe the
  # schema its services built, and clearing the pair would delete the running one
  # beside it. So reuse what is up, replace only what is gone.
  if running "$PG"; then
    echo "dev-infra: reusing $PG"
  else
    docker rm -f "$PG" >/dev/null 2>&1 || true
    docker run --rm -d --name "$PG" \
      -e POSTGRES_DB=feedback \
      -e POSTGRES_USER=feedback \
      -e POSTGRES_PASSWORD="$PG_PASSWORD" \
      -p "127.0.0.1:$PG_PORT:5432" \
      postgres:17-alpine >/dev/null
  fi
  if running "$MQ"; then
    echo "dev-infra: reusing $MQ"
  else
    docker rm -f "$MQ" >/dev/null 2>&1 || true
    docker run --rm -d --name "$MQ" \
      -e RABBITMQ_DEFAULT_USER=feedback \
      -e RABBITMQ_DEFAULT_PASS="$MQ_PASSWORD" \
      -p "127.0.0.1:$MQ_PORT:5672" \
      rabbitmq:4.1-alpine >/dev/null
  fi
  wait_ready postgres docker exec "$PG" pg_isready -U feedback -d feedback
  ensure_focus_database
  wait_ready rabbitmq docker exec "$MQ" rabbitmq-diagnostics -q ping
  echo "dev-infra: postgres 127.0.0.1:$PG_PORT  rabbitmq 127.0.0.1:$MQ_PORT"
}

# focus-service owns its own database on this server (FOCUS_DB_URL in
# .env.development). Creating it here keeps `npm run dev` free of a manual step;
# `CREATE DATABASE` has no IF NOT EXISTS, so the check runs first.
ensure_focus_database() {
  docker exec "$PG" psql -U feedback -d feedback -tAc \
    "SELECT 1 FROM pg_database WHERE datname='focus'" | grep -q 1 && return 0
  docker exec "$PG" psql -U feedback -d feedback -c "CREATE DATABASE focus OWNER feedback" >/dev/null
}

down() {
  docker rm -f "$PG" "$MQ" >/dev/null 2>&1 || true
  echo "dev-infra: removed $PG $MQ"
}

case "${1:-up}" in
  up) up ;;
  down) down ;;
  status) docker ps --filter "name=$PG" --filter "name=$MQ" ;;
  *)
    echo "usage: $0 up|down|status" >&2
    exit 2
    ;;
esac
