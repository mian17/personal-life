#!/usr/bin/env bash
# setup-dev-env.sh — create a ready-to-run `.env.development` for `npm run dev:build`.
#
# Usage: scripts/setup-dev-env.sh [TARGET_DIR]     (default: current directory)
#
# Standalone. Does NOT run npm and is not wired into any npm script.
# Hard rule: never replaces an existing .env.development. If TARGET already has
# one, this script exits 0 without touching it.
#
# Values are picked up read-only from this checkout's own `.env.development`
# (then `.env`) so master keys stay continuous with any copied data dirs; keys
# not found there are generated fresh (openssl rand -base64 32).
set -euo pipefail

TARGET="${1:-$PWD}"
BASE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$TARGET/.env.development"

if [ -e "$DEST" ]; then
  echo "exists, leaving untouched: $DEST" >&2
  exit 0
fi

# pick KEY -> value from the base checkout's .env.development, then .env.
pick() {
  for f in "$BASE/.env.development" "$BASE/.env"; do
    [ -f "$f" ] || continue
    v="$(grep -m1 "^$1=" "$f" | cut -d= -f2- || true)"
    [ -n "$v" ] && { printf '%s' "$v"; return 0; }
  done
  return 1
}

# secret_or_gen KEY -> pick, or generate 32 random bytes base64.
secret_or_gen() { pick "$1" || openssl rand -base64 32; }

# Throwaway infra credentials for the dev pair (scripts/dev-infra.sh reads
# these back and starts the containers with them). Random per generation:
# the containers hold no data worth carrying across runs.
FB_DB_PW="$(openssl rand -hex 16)"
FB_MQ_PW="$(openssl rand -hex 16)"


cat > "$DEST" <<EOF
# Generated by scripts/setup-dev-env.sh — dev only, gitignored.
# Ready for: npm run dev:build   (ports 3100-3108 must be free)

NODE_ENV=development
DB_PATH=data/scratch.db
PORT=3101
WEB_PORT=3100

# BFF -> ecosystem services.
API_URL=http://127.0.0.1:3101
TAGS_API_URL=http://127.0.0.1:3104
TODO_API_URL=http://127.0.0.1:3105
FEEDBACK_API_URL=http://127.0.0.1:3108
MEAL_API_URL=http://127.0.0.1:3106

# --- content-encryption master keys (per-service custody) -------------------
NOTE_MASTER_KEY=$(secret_or_gen NOTE_MASTER_KEY)
TAGS_MASTER_KEY=$(secret_or_gen TAGS_MASTER_KEY)
TODO_MASTER_KEY=$(secret_or_gen TODO_MASTER_KEY)
MEAL_MASTER_KEY=$(secret_or_gen MEAL_MASTER_KEY)
FEEDBACK_MASTER_KEY=$(secret_or_gen FEEDBACK_MASTER_KEY)

# --- feedback service: throwaway pair from scripts/dev-infra.sh
# 5433/5673, never the compose pair on 5432/5672: production owns those ports.
# FEEDBACK_DB_PASSWORD / FEEDBACK_RABBITMQ_PASSWORD are the same values
# dev-infra.sh hands to the containers.
FEEDBACK_DB_PASSWORD=${FB_DB_PW}
FEEDBACK_RABBITMQ_PASSWORD=${FB_MQ_PW}
FEEDBACK_DB_URL=postgresql://feedback:${FB_DB_PW}@127.0.0.1:5433/feedback
RABBITMQ_URL=amqp://feedback:${FB_MQ_PW}@127.0.0.1:5673

# --- todo-service -----------------------------------------------------------
TODO_TIMEZONE=Asia/Ho_Chi_Minh
# Web Push (VAPID) unset => reminder sweep stays off, service still boots.
# Generate once with: npx web-push generate-vapid-keys
# TODO_VAPID_PUBLIC_KEY=
# TODO_VAPID_PRIVATE_KEY=
# TODO_VAPID_SUBJECT=mailto:you@example.com

OWNER_LOGIN=your-login@example.com
NEXT_TELEMETRY_DISABLED=1

# --- IdP / OIDC (dev) -------------------------------------------------------
# Dev user seeded on every run (idempotent), login: dev / test123
SEED_USERNAME=dev
SEED_PASSWORD=test123
IDP_ISSUER=http://127.0.0.1:3102
OIDC_APP_CLIENT_ID=app
OIDC_APP_CLIENT_SECRET=dev-secret-not-a-real-secret
OIDC_APP_REDIRECT_URI=http://127.0.0.1:3100/auth/callback
OIDC_APP_REDIRECT_URIS=http://localhost:3100/auth/callback,http://127.0.0.1:3100/auth/callback
OIDC_DEFAULT_RESOURCE=https://note-service
OIDC_AUDIENCE_MAP=https://note-service=life-api,https://tags-service=life-api,https://todo-service=life-api,https://meal-service=life-api

# --- meal-service photo pipeline (optional; each degrades gracefully) -------
# GEMINI_API_KEY=        # photo estimate off until set
# GEMINI_MODEL=
# GEMINI_API_BASE=
# USDA_API_KEY=          # USDA resolution off until set (DEMO_KEY = public, rate-limited)
# USDA_API_BASE=

# --- e2e harness (apps/app/test/e2e) ----------------------------------------
# Read by both Playwright configs (test/e2e/env-file.ts), so `npm run test:e2e`
# from the repo root picks these up without prefixing the command. Only
# harness-owned names are adopted — master keys in this file never reach a
# harness child process. Shell values win over the file.
#
# Slots this machine hands out to concurrent e2e runs, 1-9 (default 1: one run
# builds and binds at a time, every other attempt queues). Raise only when the
# box can build that many stacks at once — five parallel `next build`s OOM a
# 16 GB machine.
# E2E_CONCURRENCY=1
# How long an attempt queues before it reports E2E_QUEUE_TIMEOUT (ms).
# E2E_QUEUE_ACQUIRE_GRACE_MS=480000
# How long a claim may go unreleased before a dead run's slot is reclaimed (ms).
# E2E_SLOT_MAX_AGE_MS=1800000
EOF

chmod 600 "$DEST"
echo "wrote $DEST (chmod 600)"
echo "next: cd $TARGET && npm ci && npm run dev:build"
